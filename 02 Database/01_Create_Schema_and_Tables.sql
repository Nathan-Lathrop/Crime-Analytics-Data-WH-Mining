-- Create the data warehouse schema
CREATE SCHEMA IF NOT EXISTS crime_dw;

-- ==========================================
-- DATE DIMENSION
-- ==========================================

CREATE TABLE IF NOT EXISTS crime_dw.dim_date (
    date_key       INTEGER PRIMARY KEY,
    full_date      DATE UNIQUE NOT NULL,
    year           SMALLINT NOT NULL,
    quarter        SMALLINT NOT NULL,
    month          SMALLINT NOT NULL,
    month_name     VARCHAR(12) NOT NULL,
    day_of_month   SMALLINT NOT NULL,
    day_of_week    SMALLINT NOT NULL,
    day_name       VARCHAR(12) NOT NULL,
    is_weekend     BOOLEAN NOT NULL
);

-- ==========================================
-- TIME DIMENSION
-- ==========================================

CREATE TABLE IF NOT EXISTS crime_dw.dim_time (
    time_key       INTEGER PRIMARY KEY,
    time_value     TIME UNIQUE NOT NULL,
    hour           SMALLINT NOT NULL,
    minute         SMALLINT NOT NULL,
    time_period    VARCHAR(20) NOT NULL
);

-- ==========================================
-- LOCATION DIMENSION
-- ==========================================

CREATE TABLE IF NOT EXISTS crime_dw.dim_location (
    location_key   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    location       TEXT NOT NULL,
    beat           VARCHAR(30),
    neighborhood   VARCHAR(150),
    npu            VARCHAR(30),
    latitude       NUMERIC(10,6),
    longitude      NUMERIC(10,6),

    UNIQUE NULLS NOT DISTINCT
    (location, beat, neighborhood, npu, latitude, longitude)
);

-- ==========================================
-- CRIME TYPE DIMENSION
-- ==========================================

CREATE TABLE IF NOT EXISTS crime_dw.dim_crime_type (
    crime_type_key INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ucr_literal    VARCHAR(150) UNIQUE NOT NULL
);

-- ==========================================
-- FACT TABLE
-- ==========================================

CREATE TABLE IF NOT EXISTS crime_dw.fact_crime (
    crime_fact_key BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    report_number  VARCHAR(50),
    report_date_key INTEGER REFERENCES crime_dw.dim_date(date_key),
    occur_date_key  INTEGER REFERENCES crime_dw.dim_date(date_key),
    possible_date_key INTEGER REFERENCES crime_dw.dim_date(date_key),
    occur_time_key    INTEGER REFERENCES crime_dw.dim_time(time_key),
    possible_time_key INTEGER REFERENCES crime_dw.dim_time(time_key),
    location_key   BIGINT NOT NULL REFERENCES crime_dw.dim_location(location_key),
    crime_type_key INTEGER NOT NULL REFERENCES crime_dw.dim_crime_type(crime_type_key),
    incident_count SMALLINT NOT NULL DEFAULT 1
        CHECK (incident_count = 1)
);

-- ==========================================
-- FACT TABLE INDEXES
-- ==========================================

CREATE INDEX IF NOT EXISTS idx_fact_crime_occur_date
    ON crime_dw.fact_crime(occur_date_key);

CREATE INDEX IF NOT EXISTS idx_fact_crime_location
    ON crime_dw.fact_crime(location_key);

CREATE INDEX IF NOT EXISTS idx_fact_crime_type
    ON crime_dw.fact_crime(crime_type_key);